import { Router } from 'express';
import { authenticate } from '../middleware/authorization.middleware.js';
import { protectSessionMutation } from '../middleware/session-cookie.middleware.js';
import * as controller from '../controllers/application.controller.js';
/** Session middleware runs before all operations; service guards enforce roles, grants and ownership. */
export const applicationRouter = Router();
applicationRouter.use(authenticate);
applicationRouter.get('/', controller.list());
applicationRouter.post('/', protectSessionMutation, controller.submit);
applicationRouter.get('/:id', controller.get());
applicationRouter.patch('/:id/withdraw', protectSessionMutation, controller.withdraw);
applicationRouter.get('/:id/resume/download', controller.download());
export const applicationDraftRouter = Router();
applicationDraftRouter.use(authenticate);
applicationDraftRouter.get('/', controller.drafts);
applicationDraftRouter.post('/', protectSessionMutation, controller.createDraft);
applicationDraftRouter.get('/:id', controller.draft);
applicationDraftRouter.patch('/:id', protectSessionMutation, controller.updateDraft);
applicationDraftRouter.delete('/:id', protectSessionMutation, controller.deleteDraft);
applicationDraftRouter.get('/:id/resume/download', controller.download(false, true));
export const adminApplicationRouter = Router();
adminApplicationRouter.use(authenticate);
adminApplicationRouter.get('/statistics', controller.statistics);
adminApplicationRouter.get('/', controller.list(true));
adminApplicationRouter.get('/:id', controller.get(true));
adminApplicationRouter.patch('/:id/status', protectSessionMutation, controller.decision);
adminApplicationRouter.get('/:id/resume/download', controller.download(true));
export const notificationRouter = Router();
notificationRouter.use(authenticate);
notificationRouter.get('/', controller.listNotifications);
notificationRouter.patch('/read-all', protectSessionMutation, controller.readAllNotifications);
notificationRouter.patch('/:id/read', protectSessionMutation, controller.readNotification);
